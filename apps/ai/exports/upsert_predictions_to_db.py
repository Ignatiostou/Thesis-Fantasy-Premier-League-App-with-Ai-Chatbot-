import sys
import argparse
from pathlib import Path
from datetime import datetime, timezone

sys.path.insert(0, str(Path(__file__).parent.parent))

import pandas as pd

from config import settings
from db_writer import upsert_dataframe, dispose
from logging_utils import get_logger

logger = get_logger(__name__)


DB_TABLE = "player_predictions"
# Must match the DB unique index player_predictions_player_id_gameweek_model_version_key
CONFLICT_COLS = ["player_id", "gameweek", "model_version"]

REQUIRED_COLS = [
    "player_id",
    "gameweek",
    "predicted_pts_gw1",
    "predicted_pts_if_starts",
    "predicted_pts_gw3",
    "predicted_pts_gw5",
    "prob_playing",
    "prob_60_plus_mins",
    "predicted_minutes",
    "model_version",
    "confidence",
    "generated_at",
]


def find_predictions(gameweek: int | None) -> Path:
    datasets_dir = settings.datasets_dir

    if gameweek is not None:
        path = datasets_dir / f"predictions_gw{gameweek}.parquet"
        if not path.exists():
            raise FileNotFoundError(
                f"No predictions found for GW{gameweek} at {path}. "
                "Run inference/predict_next_gw.py first."
            )
        return path

    files = sorted(datasets_dir.glob("predictions_gw*.parquet"))
    if not files:
        raise FileNotFoundError(
            f"No prediction files found in {datasets_dir}. "
            "Run inference/predict_next_gw.py first."
        )

    return files[-1]


def validate_predictions(df: pd.DataFrame) -> None:
    missing = [c for c in REQUIRED_COLS if c not in df.columns]
    if missing:
        raise ValueError(f"Predictions missing required columns: {missing}")

    if df.empty:
        raise ValueError("Predictions DataFrame is empty.")

    prob_violations = (
        (df["prob_playing"] < 0)
        | (df["prob_playing"] > 1)
        | (df["prob_60_plus_mins"] < 0)
        | (df["prob_60_plus_mins"] > 1)
    )

    if prob_violations.any():
        raise ValueError(f"{int(prob_violations.sum())} rows have probability values outside [0, 1].")

    if ((df["predicted_minutes"] < 0) | (df["predicted_minutes"] > 90)).any():
        raise ValueError("Some rows have predicted_minutes outside [0, 90].")

    invalid_conf = ~df["confidence"].isin({"HIGH", "MEDIUM", "LOW"})
    if invalid_conf.any():
        bad = df.loc[invalid_conf, "confidence"].unique().tolist()
        raise ValueError(f"Invalid confidence values: {bad}")

    if (df["predicted_pts_gw1"] < 0).any():
        raise ValueError("Some rows have negative predicted_pts_gw1.")

    logger.info(
        "Validation passed: %s rows | GW%s | HIGH=%s | MEDIUM=%s | LOW=%s",
        len(df),
        int(df["gameweek"].iloc[0]),
        (df["confidence"] == "HIGH").sum(),
        (df["confidence"] == "MEDIUM").sum(),
        (df["confidence"] == "LOW").sum(),
    )


def prepare_for_db(df: pd.DataFrame) -> pd.DataFrame:
    out = df[REQUIRED_COLS].copy()

    out["player_id"] = out["player_id"].astype(int)
    out["gameweek"] = out["gameweek"].astype(int)

    for col in [
        "predicted_pts_gw1",
        "predicted_pts_if_starts",
        "predicted_pts_gw3",
        "predicted_pts_gw5",
        "prob_playing",
        "prob_60_plus_mins",
        "predicted_minutes",
    ]:
        out[col] = out[col].astype(float).round(4)

    out["model_version"] = out["model_version"].astype(str)
    out["confidence"] = out["confidence"].astype(str)

    if out["generated_at"].isna().all():
        out["generated_at"] = datetime.now(timezone.utc).isoformat()
    else:
        out["generated_at"] = out["generated_at"].astype(str)

    return out


def _delete_stale_predictions(gameweek: int, model_version: str) -> None:
    """
    Removes predictions for this GW that were generated by an older model
    version. The unique key includes model_version, so without this cleanup
    a retrained model would leave duplicate rows per player behind.
    """
    from sqlalchemy import text
    from db_writer import get_writer_engine

    engine = get_writer_engine()
    with engine.begin() as conn:
        result = conn.execute(
            text(f"DELETE FROM {DB_TABLE} WHERE gameweek = :gw AND model_version <> :mv"),
            {"gw": gameweek, "mv": model_version},
        )
    if result.rowcount:
        logger.info("Deleted %s stale predictions for GW%s (older model versions)",
                    result.rowcount, gameweek)


def upsert_predictions(predictions: pd.DataFrame, dry_run: bool = False) -> int:
    """Validates and upserts a predictions DataFrame. Returns rows written."""
    target_gw = int(predictions["gameweek"].iloc[0])

    validate_predictions(predictions)
    db_ready = prepare_for_db(predictions)

    if dry_run:
        logger.info("DRY RUN — no data written to DB.")
        logger.info("\n%s", db_ready.head(5).to_string(index=False))
        logger.info("Would upsert %s rows into %s for GW%s", len(db_ready), DB_TABLE, target_gw)
        return 0

    try:
        _delete_stale_predictions(target_gw, str(db_ready["model_version"].iloc[0]))
        count = upsert_dataframe(
            db_ready,
            table_name=DB_TABLE,
            conflict_columns=CONFLICT_COLS,
        )
        logger.info("Successfully upserted %s predictions for GW%s.", count, target_gw)
        return count
    except Exception as exc:
        logger.error("DB upsert failed: %s", exc)
        raise


def main() -> None:
    parser = argparse.ArgumentParser(description="Upsert FPL predictions into player_predictions table")
    parser.add_argument("--gameweek", type=int, default=None)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    pred_path = find_predictions(args.gameweek)
    predictions = pd.read_parquet(pred_path)

    logger.info("Loaded %s predictions from %s", len(predictions), pred_path.name)

    upsert_predictions(predictions, dry_run=args.dry_run)


if __name__ == "__main__":
    try:
        main()
    finally:
        dispose()